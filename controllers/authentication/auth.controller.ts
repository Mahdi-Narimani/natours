import { Request, Response } from 'express';
import User from '../../Models/user.model';

const signup = async (req: Request, res: Response) => {
    try {
        const newUser = await User.create(req.body);

        res.status(201).json({
            status: 'success',
            data: {
                user: newUser,
            },
        });
    } catch (error) {
        res.status(400).json({
            status: 'fail',
            message: error.message,
        });
    }
};

export { signup };
